//! Print the intermediate representation as Rust (Maud) and CSS.
//!
//! The output is plain text with a fixed layout, so the same input always
//! gives the same bytes. Each file starts with [`HEADER_MARK`].

use std::fmt::Write as _;

use crate::ir::{
    Arg, Body, Call, CssRule, Element, EnumDef, Function, Item, Module, ParamType, ROOT_ATTRS,
    VOID_TAGS,
};
use crate::names::rust_str;
use crate::tokens::TokenSet;

/// Lints that generated code allows. Generated code has unused parts and
/// many parameters by design.
const ALLOWS: &[&str] = &[
    "dead_code",
    "unused_variables",
    "clippy::doc_markdown",
    "clippy::match_same_arms",
    "clippy::module_name_repetitions",
    "clippy::needless_pass_by_value",
    "clippy::too_many_arguments",
    "clippy::too_many_lines",
];

/// The base rule for generated classes. `:where` gives it zero
/// specificity, so each class rule wins over it. It removes browser
/// defaults (button borders, list bullets, heading margins) that the design
/// does not have.
const BASE_RESET: &str = "  box-sizing: border-box;
  margin: 0;
  padding: 0;
  border: 0 solid;
  background: none;
  font: inherit;
  color: inherit;
  text-decoration: none;
  list-style: none;
";

/// The text that marks a generated file. Generation deletes only files
/// that start with it.
pub const HEADER_MARK: &str = "@generated by autumn-figma";

/// The source of the generated files.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Header {
    /// The Figma file key.
    pub file_key: String,
    /// The Figma file version, if known.
    pub version: Option<String>,
    /// The Figma file name.
    pub file_name: String,
}

impl Header {
    /// The first line of each file, without the comment marker.
    #[must_use]
    pub fn line(&self) -> String {
        let version = self
            .version
            .as_deref()
            .map_or_else(String::new, |v| format!(" (version {})", one_line(v)));
        format!(
            "{HEADER_MARK} from Figma file {}{version}. Do not edit.",
            one_line(&self.file_key)
        )
    }
}

/// The Rust text of one page module.
#[must_use]
pub fn module(module: &Module, header: &Header) -> String {
    let mut out = format!(
        "// {}\n//! Figma page \"{}\".\n\nuse maud::{{Markup, html}};\n",
        header.line(),
        one_line(&module.page)
    );
    for e in &module.enums {
        out.push('\n');
        enum_def(&mut out, e);
    }
    for f in &module.functions {
        out.push('\n');
        function(&mut out, f);
    }
    out
}

/// Text on one line, for comments.
fn one_line(text: &str) -> String {
    text.replace(['\n', '\r'], " ")
}

fn indent(out: &mut String, level: usize) {
    for _ in 0..level {
        out.push_str("    ");
    }
}

fn enum_def(out: &mut String, e: &EnumDef) {
    let _ = writeln!(out, "/// {}", one_line(&e.doc));
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]\n");
    let _ = writeln!(out, "pub enum {} {{", e.name);
    for (i, (ident, value)) in e.variants.iter().enumerate() {
        let _ = writeln!(out, "    /// Figma value \"{}\".", one_line(value));
        if i == e.default {
            out.push_str("    #[default]\n");
        }
        let _ = writeln!(out, "    {ident},");
    }
    out.push_str("}\n");
}

fn param_type(ty: &ParamType) -> String {
    match ty {
        ParamType::Str => "&str".to_owned(),
        ParamType::Bool => "bool".to_owned(),
        ParamType::Markup => "Markup".to_owned(),
        ParamType::Enum(name) => name.clone(),
        ParamType::Attrs => "&super::Attrs<'_>".to_owned(),
    }
}

fn function(out: &mut String, f: &Function) {
    let _ = writeln!(out, "/// {}", one_line(&f.doc));
    out.push_str("#[must_use]\n");
    if f.params.is_empty() {
        let _ = writeln!(out, "pub fn {}() -> Markup {{", f.name);
    } else {
        let _ = writeln!(out, "pub fn {}(", f.name);
        for p in &f.params {
            let _ = writeln!(out, "    {}: {},", p.name, param_type(&p.ty));
        }
        out.push_str(") -> Markup {\n");
    }
    match &f.body {
        Body::Single(items) => template(out, items, 1, ""),
        Body::Match { on, arms, fallback } => {
            let scrutinee = if on.len() == 1 {
                on[0].clone()
            } else {
                format!("({})", on.join(", "))
            };
            let _ = writeln!(out, "    match {scrutinee} {{");
            for arm in arms {
                let pattern = if arm.pattern.len() == 1 {
                    arm.pattern[0].clone()
                } else {
                    format!("({})", arm.pattern.join(", "))
                };
                indent(out, 2);
                let _ = write!(out, "{pattern} => ");
                template(out, &arm.body, 2, ",");
            }
            if let Some(body) = fallback {
                out.push_str("        _ => ");
                template(out, body, 2, ",");
            }
            out.push_str("    }\n");
        }
    }
    out.push_str("}\n");
}

/// Write `html! { ... }` with the items at `level + 1`, then `suffix`.
/// The caller writes the indent of the first line.
fn template(out: &mut String, items: &[Item], level: usize, suffix: &str) {
    if level == 1 {
        indent(out, 1);
    }
    if items.is_empty() {
        let _ = writeln!(out, "html! {{}}{suffix}");
        return;
    }
    out.push_str("html! {\n");
    for item in items {
        self::item(out, item, level + 1);
    }
    indent(out, level);
    let _ = writeln!(out, "}}{suffix}");
}

fn item(out: &mut String, item: &Item, level: usize) {
    match item {
        Item::Element(e) => element(out, e, level),
        Item::Text(text) => {
            for (i, line) in text.split('\n').enumerate() {
                if i > 0 {
                    indent(out, level);
                    out.push_str("br;\n");
                }
                indent(out, level);
                let _ = writeln!(out, "{}", rust_str(line));
            }
        }
        Item::Param(name) => {
            indent(out, level);
            let _ = writeln!(out, "({name})");
        }
        Item::Call(call) => {
            indent(out, level);
            self::call(out, call, level);
            out.push('\n');
        }
        Item::If { cond, body } => {
            indent(out, level);
            let _ = writeln!(out, "@if {cond} {{");
            for i in body {
                self::item(out, i, level + 1);
            }
            indent(out, level);
            out.push_str("}\n");
        }
    }
}

fn open_tag(e: &Element) -> String {
    let mut open = e.tag.clone();
    if let Some(class) = &e.class {
        let _ = write!(open, " class={}", rust_str(class));
    }
    if let Some(id) = &e.id {
        let _ = write!(open, " id={}", rust_str(id));
    }
    for (name, value) in &e.attrs {
        let _ = write!(open, " {}={}", rust_str(name), rust_str(value));
    }
    if e.root_attrs {
        for (html, field) in ROOT_ATTRS {
            let taken = (*html == "id" && e.id.is_some()) || e.attrs.iter().any(|(n, _)| n == html);
            if !taken {
                let _ = write!(open, " {}=[attrs.{field}]", rust_str(html));
            }
        }
    }
    open
}

fn element(out: &mut String, e: &Element, level: usize) {
    let open = open_tag(e);
    indent(out, level);
    if VOID_TAGS.contains(&e.tag.as_str()) {
        let _ = writeln!(out, "{open};");
        return;
    }
    match e.children.as_slice() {
        [] => {
            let _ = writeln!(out, "{open} {{}}");
        }
        [Item::Text(t)] if !t.contains('\n') => {
            let _ = writeln!(out, "{open} {{ {} }}", rust_str(t));
        }
        [Item::Param(p)] => {
            let _ = writeln!(out, "{open} {{ ({p}) }}");
        }
        children => {
            let _ = writeln!(out, "{open} {{");
            for child in children {
                item(out, child, level + 1);
            }
            indent(out, level);
            out.push_str("}\n");
        }
    }
}

/// Write `(path(args))` without a final newline. The caller writes the
/// indent of the first line.
fn call(out: &mut String, call: &Call, level: usize) {
    let multi_line = call
        .args
        .iter()
        .any(|a| matches!(a, Arg::Markup(items) if !items.is_empty()));
    if !multi_line {
        let args: Vec<String> = call.args.iter().map(simple_arg).collect();
        let _ = write!(out, "({}({}))", call.path, args.join(", "));
        return;
    }
    let _ = writeln!(out, "({}(", call.path);
    for arg in &call.args {
        indent(out, level + 1);
        match arg {
            Arg::Markup(items) if !items.is_empty() => {
                out.push_str("html! {\n");
                for i in items {
                    item(out, i, level + 2);
                }
                indent(out, level + 1);
                out.push_str("},\n");
            }
            other => {
                let _ = writeln!(out, "{},", simple_arg(other));
            }
        }
    }
    indent(out, level);
    out.push_str("))");
}

fn simple_arg(arg: &Arg) -> String {
    match arg {
        Arg::Str(text) => rust_str(text),
        Arg::Bool(b) => b.to_string(),
        Arg::Path(path) => path.clone(),
        Arg::Markup(_) => "html! {}".to_owned(),
        Arg::Attrs(fields) if fields.is_empty() => "&super::Attrs::NONE".to_owned(),
        Arg::Attrs(fields) => {
            let set: Vec<String> = fields
                .iter()
                .map(|(field, value)| format!("{field}: Some({})", rust_str(value)))
                .collect();
            format!(
                "&super::Attrs {{ {}, ..super::Attrs::NONE }}",
                set.join(", ")
            )
        }
    }
}

/// The Rust text of `mod.rs`: lint allows, page modules, and `Attrs`.
#[must_use]
pub fn mod_rs(modules: &[Module], header: &Header) -> String {
    let mut out = format!(
        "// {}\n//! Figma file \"{}\" as Maud components.\n//!\n//! Do not edit these files. Change the design or `figma.toml`, then run\n//! `autumn-figma generate`.\n\n#![allow(\n",
        header.line(),
        one_line(&header.file_name)
    );
    // rustfmt puts no comma after the last lint.
    let lints: Vec<String> = ALLOWS.iter().map(|l| format!("    {l}")).collect();
    out.push_str(&lints.join(",\n"));
    out.push_str("\n)]\n\n");
    for m in modules {
        let _ = writeln!(out, "#[rustfmt::skip]\npub mod {};", m.name);
    }
    out.push_str(
        "\n/// Attributes for the root element of a component.\n///\n/// Set them at the call site to add htmx behavior:\n///\n/// ```ignore\n/// todo_row(false, \"New\", &Attrs { hx_delete: Some(\"/todos/7\"), ..Attrs::NONE })\n/// ```\n#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]\npub struct Attrs<'a> {\n",
    );
    for (html, field) in ROOT_ATTRS {
        let _ = writeln!(
            out,
            "    /// The `{html}` attribute.\n    pub {field}: Option<&'a str>,"
        );
    }
    out.push_str(
        "}\n\nimpl Attrs<'static> {\n    /// No attributes.\n    pub const NONE: Self = Self {\n",
    );
    for (_, field) in ROOT_ATTRS {
        let _ = writeln!(out, "        {field}: None,");
    }
    out.push_str("    };\n}\n");
    out
}

/// The CSS text: tokens, a base rule for `prefix`, and the rules.
#[must_use]
pub fn css(tokens: &TokenSet, prefix: &str, rules: &[CssRule], header: &Header) -> String {
    let mut out = format!("/* {} */\n", header.line().replace("*/", "* /"));
    if !tokens.is_empty() {
        out.push('\n');
        out.push_str(&tokens.css());
    }
    let _ = write!(
        out,
        "\n:where([class^=\"{prefix}-\"], [class*=\" {prefix}-\"]) {{\n{BASE_RESET}}}\n"
    );
    for rule in rules.iter().filter(|r| !r.decls.is_empty()) {
        let _ = writeln!(out, "\n.{} {{", rule.class);
        for (property, value) in &rule.decls.0 {
            let _ = writeln!(out, "  {property}: {value};");
        }
        out.push_str("}\n");
    }
    out
}

