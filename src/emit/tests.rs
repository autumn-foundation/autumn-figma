#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::collections::BTreeMap;

use super::*;
use crate::ir::{Arg, Arm, Body, Call, Element, EnumDef, Function, Item, Param, ParamType};
use crate::style::Decls;

fn header() -> Header {
    Header {
        file_key: "AbC".into(),
        version: Some("42".into()),
        file_name: "Todo".into(),
    }
}

fn el(tag: &str, class: &str, children: Vec<Item>) -> Element {
    Element {
        tag: tag.into(),
        class: Some(class.into()),
        children,
        ..Element::default()
    }
}

#[test]
fn header_line() {
    assert_eq!(
        header().line(),
        "@generated by autumn-figma from Figma file AbC (version 42). Do not edit."
    );
    let h = Header {
        version: None,
        ..header()
    };
    assert_eq!(
        h.line(),
        "@generated by autumn-figma from Figma file AbC. Do not edit."
    );
}

#[test]
fn a_screen_module() {
    let mut form = el(
        "form",
        "fg-todos__form",
        vec![
            Item::Element(Element {
                tag: "input".into(),
                class: Some("fg-todos__input".into()),
                attrs: vec![("placeholder".into(), "What \"now\"?".into())],
                ..Element::default()
            }),
            Item::Call(Call {
                path: "super::components::icon".into(),
                args: vec![Arg::Attrs(vec![])],
            }),
        ],
    );
    form.attrs = vec![("hx-post".into(), "/todos".into())];
    let list = Element {
        id: Some("todo-list".into()),
        ..el("ul", "fg-todos__list", vec![Item::Param("items".into())])
    };
    let m = Module {
        name: "screens".into(),
        page: "Screens".into(),
        enums: vec![],
        functions: vec![Function {
            name: "todos".into(),
            doc: "Figma frame \"Todos\" (node 2:1).".into(),
            params: vec![
                Param {
                    name: "items".into(),
                    ty: ParamType::Markup,
                },
                Param {
                    name: "count".into(),
                    ty: ParamType::Str,
                },
            ],
            body: Body::Single(vec![Item::Element(el(
                "div",
                "fg-todos",
                vec![
                    Item::Element(el(
                        "h1",
                        "fg-todos__title",
                        vec![Item::Text("My todos".into())],
                    )),
                    Item::Element(form),
                    Item::Element(list),
                    Item::Element(el("p", "fg-todos__note", vec![Item::Text("a\nb".into())])),
                    Item::Element(el(
                        "span",
                        "fg-todos__count",
                        vec![Item::Param("count".into())],
                    )),
                    Item::Element(Element {
                        tag: "div".into(),
                        ..Element::default()
                    }),
                ],
            ))]),
        }],
    };
    let expected = r#"// @generated by autumn-figma from Figma file AbC (version 42). Do not edit.
//! Figma page "Screens".

use maud::{Markup, html};

/// Figma frame "Todos" (node 2:1).
#[must_use]
pub fn todos(
    items: Markup,
    count: &str,
) -> Markup {
    html! {
        div class="fg-todos" {
            h1 class="fg-todos__title" { "My todos" }
            form class="fg-todos__form" "hx-post"="/todos" {
                input class="fg-todos__input" "placeholder"="What \"now\"?";
                (super::components::icon(&super::Attrs::NONE))
            }
            ul class="fg-todos__list" id="todo-list" { (items) }
            p class="fg-todos__note" {
                "a"
                br;
                "b"
            }
            span class="fg-todos__count" { (count) }
            div {}
        }
    }
}
"#;
    assert_eq!(module(&m, &header()), expected);
}

#[test]
fn a_component_set_module() {
    let root = |class: &str, children| {
        Item::Element(Element {
            tag: "button".into(),
            class: Some(class.into()),
            attrs: vec![("type".into(), "button".into())],
            root_attrs: true,
            children,
            ..Element::default()
        })
    };
    let m = Module {
        name: "components".into(),
        page: "Components".into(),
        enums: vec![EnumDef {
            name: "ButtonSize".into(),
            doc: "Variant property \"Size\" of \"Button\".".into(),
            variants: vec![
                ("Large".into(), "Large".into()),
                ("Small".into(), "Small".into()),
            ],
            default: 1,
        }],
        functions: vec![Function {
            name: "button".into(),
            doc: "Figma component set \"Button\" (node 1:10).".into(),
            params: vec![
                Param {
                    name: "size".into(),
                    ty: ParamType::Enum("ButtonSize".into()),
                },
                Param {
                    name: "icon".into(),
                    ty: ParamType::Markup,
                },
                Param {
                    name: "show_icon".into(),
                    ty: ParamType::Bool,
                },
                Param {
                    name: "attrs".into(),
                    ty: ParamType::Attrs,
                },
            ],
            body: Body::Match {
                on: vec!["size".into()],
                arms: vec![
                    Arm {
                        pattern: vec!["ButtonSize::Large".into()],
                        body: vec![root(
                            "fg-button--large",
                            vec![Item::If {
                                cond: "show_icon".into(),
                                body: vec![Item::Param("icon".into())],
                            }],
                        )],
                    },
                    Arm {
                        pattern: vec!["ButtonSize::Small".into()],
                        body: vec![root("fg-button--small", vec![])],
                    },
                ],
                fallback: None,
            },
        }],
    };
    let out = module(&m, &header());
    let expected_enum = r#"/// Variant property "Size" of "Button".
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum ButtonSize {
    /// Figma value "Large".
    Large,
    /// Figma value "Small".
    #[default]
    Small,
}
"#;
    assert!(out.contains(expected_enum), "{out}");
    assert!(
        out.contains("    attrs: &super::Attrs<'_>,\n) -> Markup {\n    match size {\n        ButtonSize::Large => html! {\n"),
        "{out}"
    );
    assert!(
        out.contains("            button class=(super::classes(\"fg-button--large\", attrs.class)) \"type\"=\"button\" \"id\"=[attrs.id] \"name\"=[attrs.name]"),
        "{out}"
    );
    assert!(
        !out.contains("\"type\"=[attrs.type_]"),
        "static type wins: {out}"
    );
    assert!(out.contains("\"hx-post\"=[attrs.hx_post]"), "{out}");
    assert!(
        out.contains(
            "                @if show_icon {\n                    (icon)\n                }\n"
        ),
        "{out}"
    );
    assert!(
        out.contains("        },\n        ButtonSize::Small => html! {\n"),
        "{out}"
    );
    assert!(out.ends_with("        },\n    }\n}\n"), "{out}");
}

#[test]
fn match_on_two_enums_with_a_fallback() {
    let m = Module {
        name: "c".into(),
        page: "C".into(),
        enums: vec![],
        functions: vec![Function {
            name: "chip".into(),
            doc: "Chip.".into(),
            params: vec![],
            body: Body::Match {
                on: vec!["size".into(), "state".into()],
                arms: vec![Arm {
                    pattern: vec!["A::X".into(), "B::Y".into()],
                    body: vec![Item::Text("x".into())],
                }],
                fallback: Some(vec![Item::Text("f".into())]),
            },
        }],
    };
    let out = module(&m, &header());
    assert!(out.contains("    match (size, state) {\n        (A::X, B::Y) => html! {\n            \"x\"\n        },\n        _ => html! {\n            \"f\"\n        },\n    }\n"), "{out}");
}

#[test]
fn calls_with_markup_arguments_span_lines() {
    let call = Item::Call(Call {
        path: "button".into(),
        args: vec![
            Arg::Path("ButtonSize::Small".into()),
            Arg::Markup(vec![Item::Call(Call {
                path: "icon".into(),
                args: vec![Arg::Attrs(vec![])],
            })]),
            Arg::Markup(vec![]),
            Arg::Str("Add \"it\"".into()),
            Arg::Bool(true),
            Arg::Attrs(vec![("type_".into(), "submit".into())]),
        ],
    });
    let m = Module {
        name: "s".into(),
        page: "S".into(),
        enums: vec![],
        functions: vec![Function {
            name: "f".into(),
            doc: "F.".into(),
            params: vec![],
            body: Body::Single(vec![call]),
        }],
    };
    let out = module(&m, &header());
    let expected = r#"pub fn f() -> Markup {
    html! {
        (button(
            ButtonSize::Small,
            html! {
                (icon(&super::Attrs::NONE))
            },
            html! {},
            "Add \"it\"",
            true,
            &super::Attrs { type_: Some("submit"), ..super::Attrs::NONE },
        ))
    }
}
"#;
    assert!(out.contains(expected), "{out}");
}

#[test]
fn mod_rs_lists_modules_and_attrs() {
    let m = |name: &str| Module {
        name: name.into(),
        page: name.into(),
        enums: vec![],
        functions: vec![],
    };
    let out = mod_rs(&[m("components"), m("screens")], &header());
    assert!(out.starts_with("// @generated by autumn-figma"), "{out}");
    assert!(out.contains("#![allow(\n"), "{out}");
    assert!(
        out.contains("#[rustfmt::skip]\npub mod components;\n#[rustfmt::skip]\npub mod screens;\n"),
        "{out}"
    );
    assert!(out.contains("pub struct Attrs<'a> {\n"), "{out}");
    assert!(out.contains("    pub hx_post: Option<&'a str>,\n"), "{out}");
    assert!(out.contains("    pub type_: Option<&'a str>,\n"), "{out}");
    for field in [
        "hx_swap_oob",
        "hx_headers",
        "hx_ext",
        "hx_sync",
        "hx_disabled_elt",
        "role",
        "title",
        "disabled",
        "class",
    ] {
        assert!(
            out.contains(&format!("    pub {field}: Option<&'a str>,\n")),
            "{field}: {out}"
        );
    }
    assert!(out.contains("impl Attrs<'static> {\n"), "{out}");
    assert!(out.contains("    pub const NONE: Self = Self {\n"), "{out}");
}

#[test]
fn css_text() {
    let mut tokens = TokenSet::new(None, &BTreeMap::new(), &mut Vec::new());
    tokens.style("S:1", "Brand", || Some("#ffffff".into()));
    let mut decls = Decls::default();
    decls.push("display", "flex");
    decls.push("gap", "8px");
    let rules = vec![
        CssRule {
            class: "fg-a".into(),
            decls,
            boost: false,
        },
        CssRule {
            class: "fg-b".into(),
            decls: Decls::default(),
            boost: false,
        },
    ];
    let out = css(&tokens, "fg", &rules, &header());
    let expected = r#"/* @generated by autumn-figma from Figma file AbC (version 42). Do not edit. */

:root {
  --brand: #ffffff;
}

:where([class^="fg-"], [class*=" fg-"]) {
  box-sizing: border-box;
  margin: 0;
  padding: 0;
  border: 0 solid;
  background: none;
  font: inherit;
  color: inherit;
  text-decoration: none;
  list-style: none;
}

.fg-a {
  display: flex;
  gap: 8px;
}
"#;
    assert_eq!(out, expected);
}

#[test]
fn comment_text_is_safe_for_rustc_and_rustdoc() {
    // Regression: U+202E in a comment fails rustc's
    // text_direction_codepoint_in_comment lint; raw HTML reaches rustdoc.
    let m = Module {
        name: "p".into(),
        page: "Page \u{202e}<script>alert(1)</script> & co".into(),
        enums: vec![],
        functions: vec![],
    };
    let h = Header {
        version: Some("1\u{2066}2".into()),
        ..header()
    };
    let out = module(&m, &h);
    assert!(
        !out.contains('\u{202e}') && !out.contains('\u{2066}'),
        "{out:?}"
    );
    assert!(
        out.contains("&lt;script&gt;alert(1)&lt;/script&gt; &amp; co"),
        "{out}"
    );
    let rs = mod_rs(
        &[],
        &Header {
            file_name: "<b>\u{200f}".into(),
            ..header()
        },
    );
    assert!(rs.contains("&lt;b&gt;") && !rs.contains('\u{200f}'), "{rs}");
}
